export function pixelColumns(text: string) {
  return Math.max(1, text.length * 6 - 1)
}

// Draws text filling the box, one rect per lit font pixel.
export function drawPixelText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, w: number, h: number) {
  const cw = w / pixelColumns(text)
  const ch = h / 7
  ;[...text.toUpperCase()].forEach((char, i) => {
    const rows = (glyphs[char] ?? '').split(' ')
    rows.forEach((row, ry) => {
      ;[...row].forEach((on, rx) => {
        if (on === '#') ctx.fillRect(x + (i * 6 + rx) * cw, y + ry * ch, Math.ceil(cw), Math.ceil(ch))
      })
    })
  })
}
